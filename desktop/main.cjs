function resolveStartupMode(savedMode, platform = process.platform, hiddenTest = smokeTest) {
  if (hiddenTest) return 'window';
  // The Windows launcher is the desktop calendar. Older releases persisted
  // "window" after a temporary mode switch, which made the next launch look
  // like a conventional application instead of the requested desktop surface.
  if (platform === 'win32') return 'desktop';
  const preferred = ['window', 'desktop', 'fullscreen'].includes(savedMode) ? savedMode : 'desktop';
  return preferred === 'desktop' && platform !== 'win32' ? 'window' : preferred;
}

function errorMessage(error) {
  return typeof error?.message === 'string' ? error.message.slice(0, 700) : String(error).slice(0, 700);
}

function helperPath() {
  // electron-builder must unpack desktop.ps1 because Windows PowerShell cannot read ASAR.
  const unpacked = path.join(process.resourcesPath, 'app.asar.unpacked', 'desktop', 'desktop.ps1');
  return app.isPackaged && fs.existsSync(unpacked) ? unpacked : path.join(__dirname, 'desktop.ps1');
}

function nativeHandle(window) {
  const handle = window.getNativeWindowHandle();
  return handle.length >= 8 ? handle.readBigUInt64LE(0).toString() : String(handle.readUInt32LE(0));
}

function widgetRect() {
  const work = screen.getPrimaryDisplay().workArea;
  // Electron uses DIP, while the Explorer helper uses physical screen pixels.
  return screen.dipToScreenRect(null, work);
}

function setCalendarInteractive(interactive) {
  if (!desktopWindow || desktopWindow.isDestroyed() || !nativeState) return false;
  if (calendarInteractive !== interactive) {
    desktopWindow.setIgnoreMouseEvents(!interactive, interactive ? undefined : { forward: true });
    calendarInteractive = interactive;
  }
  return true;
}

// The calendar page tracks whether it asked for mouse input. Whenever the main
// process changes that state on its own, the page must forget its cached value;
// otherwise it never asks again and every later click falls through to Explorer.
function resetDesktopPointer() {
  setCalendarInteractive(false);
  if (desktopWindow && !desktopWindow.isDestroyed() && !desktopWindow.webContents.isDestroyed()) {
    desktopWindow.webContents.send('desktop:pointer-reset');
  }
}

function callDesktopHelper(action, state, rect) {
  if (process.platform !== 'win32') return Promise.reject(new Error('桌面常驻模式目前仅支持 Windows。'));
  if (!desktopWindow || desktopWindow.isDestroyed()) return Promise.reject(new Error('桌面日历窗口已关闭。'));
  const powershell = path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe');
  const args = ['-NoLogo', '-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-File', helperPath(),
    '-Action', action, '-Hwnd', nativeHandle(desktopWindow), '-OwnerProcessId', String(process.pid), '-Opacity', String(settings.opacity)];
  if (state) args.push('-StateBase64', Buffer.from(JSON.stringify(state), 'utf8').toString('base64'));
  if (rect) args.push('-Left', String(rect.x), '-Top', String(rect.y), '-Width', String(rect.width), '-Height', String(rect.height));
  return new Promise((resolve, reject) => {
    execFile(powershell, args, { windowsHide: true, timeout: 12_000, maxBuffer: 64 * 1024, encoding: 'utf8' }, (error, stdout, stderr) => {
      let result;
      try { result = JSON.parse(stdout.trim().replace(/^\uFEFF/, '')); } catch { /* handled below */ }
      if (result?.ok) return resolve(result);
      const failure = new Error(result?.error || (error?.killed ? '桌面连接超时，已恢复普通窗口。' : stderr.trim() || errorMessage(error || '桌面连接失败。')));
      failure.restoreState = result?.state;
      failure.rollbackError = result?.rollbackError;
      failure.uncertain = !result;
      reject(failure);
    });
  });
}

